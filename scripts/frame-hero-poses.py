"""Generate SVG display masks and uniform framing; never alter source artwork.

The source export includes disconnected scraps from neighbouring poses. Keep
the main silhouette plus nearby interior details, then fit it into a common
384px display canvas with 24px safety padding, preserving its aspect ratio.
"""
from pathlib import Path
from io import BytesIO
import base64
import json
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
rules = ['/* Generated by scripts/frame-hero-poses.py. Shared by every hero display. */']
report = {}
for path in sorted((ROOT / 'public/assets/equipment-v63').glob('*.webp')):
    if path.stem.count('-') != 1: continue
    hero, weapon = path.stem.split('-')
    alpha = np.asarray(Image.open(path).convert('RGBA'))[:, :, 3]
    labels, count = ndimage.label(alpha > 32, structure=np.ones((3, 3)))
    sizes = np.bincount(labels.ravel()); sizes[0] = 0
    main = labels == sizes.argmax()
    ys, xs = np.where(main)
    left, top, right, bottom = int(xs.min()), int(ys.min()), int(xs.max()+1), int(ys.max()+1)
    nearby = ndimage.binary_dilation(main, iterations=12)
    keep = main.copy()
    for i in range(1, count+1):
        yy, xx = np.where(labels == i)
        if not len(xx): continue
        if xx.min()>left+3 and xx.max()<right-3 and yy.min()>top+3 and yy.max()<bottom-3 and np.any(nearby[yy,xx]):
            keep[yy,xx] = True
    # A small expansion retains soft edge pixels without bringing back scraps.
    keep = ndimage.binary_dilation(keep, iterations=2)
    mask = Image.new('RGBA', (384,384), (255,255,255,0))
    mask.putalpha(Image.fromarray((keep.astype(np.uint8)*255)))
    encoded = BytesIO(); mask.save(encoded, format='PNG', optimize=True)
    scale = min(336/(right-left), 336/(bottom-top))
    x = (192-(left+right)/2)*scale/384*100
    y = (192-(top+bottom)/2)*scale/384*100
    selector = f'html body .avatar-chip.reference-equipped img.reference-hero[data-hero="{hero}"][data-equipped="{weapon}"],html body .avatar-equipped.reference-weapon[data-hero="{hero}"][data-equipped="{weapon}"] img'
    uri = 'url("data:image/png;base64,'+base64.b64encode(encoded.getvalue()).decode()+'")'
    active={'fox':{'arrow','crossbow'},'witch':{'wand'},'golem':{'hammer'},'wisp':{'dagger'},'goblin':{'sandal','spear'},'tinker':{'crossbow'}}
    if weapon in active.get(hero,set()): rules.append(selector+'{mask-image:'+uri+'!important;-webkit-mask-image:'+uri+'!important;mask-size:contain!important;mask-position:center!important;mask-repeat:no-repeat;scale:'+f'{scale:.5f};translate:{x:.4f}% {y:.4f}%'+';}')
    report[path.stem] = {'bounds':[left,top,right,bottom], 'scale':round(scale,5), 'center':[round(x,4),round(y,4)]}
(ROOT/'public/hero-poses-v130.css').write_text('\n'.join(rules)+'\n')
(ROOT/'tests/hero-frames130.json').write_text(json.dumps(report,indent=2)+'\n')
print(f'Generated consistent display frames for {len(report)} hero/weapon poses.')
